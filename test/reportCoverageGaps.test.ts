// Planned coverage the run did not get must not leave qa_report at SHIP.
//  - a qa_flow_run result is recorded as the flow's outcome (drift > CAUTION, app failure > BLOCK);
//  - a blocked exploration (unsafe actions skipped) never pairs Coverage BLOCKED with SHIP;
//  - saved flows skipped by the session budget are not covered: CAUTION, coverage PARTIAL, named.
// Hermetic: HOME is a temp dir (test/setupFakeHome.ts), no device discovery, no driver.

import { afterAll, describe, expect, it } from 'vitest';
import { mkdtempSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';

process.env.SWIPIUM_DISABLE_DEVICE_DISCOVERY = '1';

const { SessionStore } = await import('../src/session/store.js');
const { generateSessionReport } = await import('../src/services/report.js');
const { recordFlowRunOutcome } = await import('../src/tools/flow.js');
type ReportData = import('../src/report/export.js').ReportData;
type Session = import('../src/session/store.js').Session;
type FlowRunResult = import('../src/flows/run.js').FlowRunResult;

const roots: string[] = [];
afterAll(() => {
  for (const r of roots) rmSync(r, { recursive: true, force: true });
});

/** A launched app with a passing launch smoke: on its own, SHIP / COVERED. */
function launched(): { store: InstanceType<typeof SessionStore>; s: Session } {
  const root = mkdtempSync(join(tmpdir(), 'swipium-gaps-r3-'));
  roots.push(root);
  const store = new SessionStore();
  const s = store.create(root);
  s.appId = 'com.example.app';
  store.milestone(s, 'app_launch_end');
  store.addNote(s, { at: Date.now(), workflow: 'launch_smoke', outcome: 'pass', reason: 'native=ok app=ok quality=good' });
  return { store, s };
}

async function report(store: InstanceType<typeof SessionStore>, s: Session) {
  const res = await generateSessionReport(store, s, { includeCurrentDump: false });
  return { r: res.report as unknown as ReportData, text: res.summaryText };
}

function failedRun(kind: string, failureCode: FlowRunResult['failureCode']): FlowRunResult {
  return {
    name: 'fo-search',
    passed: false,
    failedAtStep: 2,
    reason: 'element "Home" not found',
    failureCode,
    steps: [
      { index: 1, phase: 'main', kind: 'tap', summary: 'tap search', ok: true },
      { index: 2, phase: 'main', kind, summary: `${kind} Home`, ok: false, failureCode },
    ],
    durationMs: 1200,
    counters: {} as FlowRunResult['counters'],
  };
}

const GENERATED = '# Generated by Swipium\nname: fo-search\nsteps: []\n';
const HAND_WRITTEN = 'name: fo-search\nsteps: []\n';

describe('qa_flow_run records its outcome on the session', () => {
  it('the baseline (launch smoke pass only) is SHIP', async () => {
    const { store, s } = launched();
    const { r } = await report(store, s);
    expect(r.executiveSummary.risk).toBe('ship');
  });

  it('a generated flow failing on a locator step is drift: CAUTION, never SHIP or BLOCK', async () => {
    const { store, s } = launched();
    recordFlowRunOutcome(store, s, failedRun('waitForVisible', 'ASSERTION_FAILED'), GENERATED);
    expect(s.notes.at(-1)).toMatchObject({ workflow: 'fo-search', outcome: 'fail', category: 'other' });
    const { r } = await report(store, s);
    expect(r.executiveSummary.risk).toBe('caution');
    expect(r.coverageVerdict?.status).toBe('BLOCKED');
  });

  it('a hand-written assertion failure is an app failure: BLOCK', async () => {
    const { store, s } = launched();
    recordFlowRunOutcome(store, s, failedRun('assertVisible', 'ASSERTION_FAILED'), HAND_WRITTEN);
    expect(s.notes.at(-1)).toMatchObject({ workflow: 'fo-search', outcome: 'fail', category: 'app_bug' });
    const { r } = await report(store, s);
    expect(r.executiveSummary.risk).toBe('block');
  });

  it('a passing run is a pass outcome; a cancelled run records nothing', async () => {
    const { store, s } = launched();
    recordFlowRunOutcome(store, s, { ...failedRun('tap', undefined), passed: true, failedAtStep: undefined }, GENERATED);
    expect(s.notes.at(-1)).toMatchObject({ workflow: 'fo-search', outcome: 'pass' });
    const before = s.notes.length;
    recordFlowRunOutcome(store, s, failedRun('tap', 'CANCELLED'), GENERATED);
    expect(s.notes.length).toBe(before);
  });
});

describe('coverage gaps are never SHIP (release_gate notes)', () => {
  it('an exploration blocked only by unsafe actions skipped: CAUTION with Coverage BLOCKED', async () => {
    const { store, s } = launched();
    store.setExploration(s, {
      at: Date.now(),
      state: 'blocked',
      stoppedReason: 'only unsafe actions left',
      summary: {
        screensVisited: 3,
        actionsTried: 5,
        workflowsFound: 2,
        blockers: 2,
        appErrors: 0,
        visualOnlyScreens: 0,
        unsafeActionsSkipped: 2,
      },
    });
    const { r } = await report(store, s);
    expect(r.coverageVerdict?.status).toBe('BLOCKED');
    expect(r.executiveSummary.risk).toBe('caution');
    expect(r.executiveSummary.reasons.join(' ')).toMatch(/exploration blocked/);
  });

  it('all saved flows skipped by the budget: CAUTION, coverage PARTIAL, flows named', async () => {
    const { store, s } = launched();
    for (const w of ['airmap-smoke', 'fo-search'])
      store.addNote(s, {
        at: Date.now(),
        workflow: w,
        outcome: 'skipped',
        category: 'intentionally_skipped',
        reason: 'budget: actions 40/40',
      });
    const { r, text } = await report(store, s);
    expect(r.executiveSummary.risk).toBe('caution');
    expect(r.coverageVerdict?.status).toBe('PARTIAL');
    expect(r.executiveSummary.reasons.join(' ')).toMatch(/2 workflow\(s\) not run.*airmap-smoke, fo-search/);
    expect(text).toMatch(/qa_start_session \{ budget \}/);
  });

  it('a flow that passed and was then skipped by the budget still counts as the pass (no coverage gap)', async () => {
    const { store, s } = launched();
    store.addNote(s, { at: Date.now() - 10, workflow: 'fo-search', outcome: 'pass', origin: 'flow', reason: 'qa_flow_run: 12 steps' });
    store.addNote(s, {
      at: Date.now(),
      workflow: 'fo-search',
      outcome: 'skipped',
      category: 'intentionally_skipped',
      origin: 'flow',
      reason: 'budget: actions 40/40',
    });
    const { r } = await report(store, s);
    expect(r.executiveSummary.risk).toBe('ship');
    expect(r.executiveSummary.reasons.join(' ')).not.toMatch(/budget/);
    expect(r.coverageVerdict?.summary).not.toMatch(/budget/);
  });

  it('a flow skipped by the budget and later run to a pass is covered again', async () => {
    const { store, s } = launched();
    store.addNote(s, {
      at: Date.now(),
      workflow: 'fo-search',
      outcome: 'skipped',
      category: 'intentionally_skipped',
      reason: 'budget: actions 40/40',
    });
    store.addNote(s, { at: Date.now(), workflow: 'fo-search', outcome: 'pass', reason: '12 steps' });
    const { r } = await report(store, s);
    expect(r.executiveSummary.risk).toBe('ship');
    expect(r.coverageVerdict?.summary).not.toMatch(/budget/);
  });
});
